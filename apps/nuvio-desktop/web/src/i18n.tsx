/** Known Portuguese backend messages, shown in English when the interface is English. */
export function translateBackendError(text: string): string {
  if (currentLanguage === "ar") {
    const exact = (Object.keys(pt) as TranslationKey[]).find((key) => pt[key] === text);
    if (exact) return ar[exact];
    for (const [key, value] of Object.entries(pt)) {
      if (value === text) return ar[key as TranslationKey] ?? text;
    }
    return text;
  }
  if (currentLanguage !== "en") return text;
  for (const [pattern, replacement] of BACKEND_EN) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  if (text === "Séries") return "Series";
  if (text === "Filmes") return "Movies";
  if (text === "Canais") return "Channels";
  return text;
}

interface I18nValue {
  language: Language;
  setLanguage(language: Language): void;
  t(key: TranslationKey, vars?: Vars): string;
}

const I18nContext = createContext<I18nValue | null>(null);

type LanguageListener = (language: Language) => void;
const languageListeners = new Set<LanguageListener>();

/** Changes the language outside React (UI test driver) and lets the provider re-render. */
export function setUILanguage(next: Language): void {
  currentLanguage = next;
  try {
    localStorage.setItem(UI_LANGUAGE_KEY, next);
  } catch {
    /* kept for this session only */
  }
  for (const listener of languageListeners) listener(next);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => readStoredLanguage());

  const setLanguage = useCallback((next: Language) => {
    setUILanguage(next);
  }, []);

  useEffect(() => {
    const listener = (next: Language) => setLanguageState(next);
    languageListeners.add(listener);
    return () => {
      languageListeners.delete(listener);
    };
  }, []);

  useEffect(() => {
    currentLanguage = language;
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);

  const value = useMemo<I18nValue>(
    () => ({ language, setLanguage, t: (key, vars) => translate(key, vars) }),
    [language, setLanguage],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("I18nProvider missing");
  return value;
}
