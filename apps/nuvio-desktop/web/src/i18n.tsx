const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, pt, ar };

type Vars = Record<string, string | number>;

function interpolate(text: string, vars?: Vars): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

function detectSystemLanguage(): Language {
  try {
    const lang = typeof navigator !== "undefined" ? (navigator.language || "") : "";
    const lower = lang.toLowerCase();
    return lower.startsWith("ar") ? "ar" : lower.startsWith("pt") ? "pt" : "en";
  } catch {
    return "en";
  }
}

function readStoredLanguage(): Language {
  try {
    const stored = localStorage.getItem(UI_LANGUAGE_KEY);
    if (stored === "pt" || stored === "en" || stored === "ar") return stored;
  } catch {
    /* no storage */
  }
  return detectSystemLanguage();
}

let currentLanguage: Language = readStoredLanguage();

if (typeof document !== "undefined") {
  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = currentLanguage === "ar" ? "rtl" : "ltr";
}

/** Current language for plain helpers outside React (formatters, backend error mapping). */
export function getLanguage(): Language {
  return currentLanguage;
}

export function locale(): string {
  return currentLanguage === "pt" ? "pt-BR" : currentLanguage === "ar" ? "ar" : "en-US";
}

export function translate(key: TranslationKey, vars?: Vars): string {
  return interpolate(dictionaries[currentLanguage][key] ?? en[key], vars);
}

/** Catalog row titles come from Rust with a Portuguese type suffix; localize just that suffix. */
export function localizeCatalogTitle(title: string): string {
  const suffixes: [string, string][] = currentLanguage === "ar"
    ? [[" - Filmes", " - أفلام"], [" - Séries", " - مسلسلات"], [" - Canais", " - قنوات"]]
    : [[" - Filmes", " - Movies"], [" - Séries", " - Series"], [" - Canais", " - Channels"]];
  if (currentLanguage === "pt") return title;
  for (const [from, to] of suffixes) {
    if (title.endsWith(from)) return title.slice(0, -from.length) + to;
  }
  return title;
}

